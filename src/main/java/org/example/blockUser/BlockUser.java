package org.example.blockUser;

public class BlockUser {
    private int idUser;
    private int blockIdUser;

    public BlockUser(int idUser, int blockIdUser) {
        this.idUser = idUser;
        this.blockIdUser = blockIdUser;
    }

    public int getIdUser() {
        return idUser;
    }

    public void setIdUser(int idUser) {
        this.idUser = idUser;
    }

    public int getBlockIdUser() {
        return blockIdUser;
    }

    public void setBlockIdUser(int blockIdUser) {
        this.blockIdUser = blockIdUser;
    }

    public BlockUser() {
    }




}
